def q(x):
    if x.denominator == 1:
        return f"({x.numerator} : Rat)"
    return f"({x.numerator} / {x.denominator} : Rat)"


def opt(x):
    return "none" if x is None else f"some {q(x)}"


def lst(xs):
    return "[" + ", ".join(xs) + "]"


def bl(b):
    return "true" if b else "false"


def read2(r):
    return f"⟨{q(r['start'])}, arr2 ({opt(r['arrivals'][0])}) ({opt(r['arrivals'][1])}), {lst(q(t) for t in r['emissions'])}, 0⟩"


def read1(v):
    return f"⟨{q(v['start'])}, fun _ => {opt(v['arrival'])}, {lst(q(t) for t in v['emissions'])}, 0⟩"


def rows(trace):
    """Layer rows top-down, as `build` consumes them."""
    return lst(lst(read2(r) for r in row) for row in reversed(trace))


def emit(meas, dmin, dmax, lessons, maxw):
    s, tim, L = meas.s, meas.tim, meas.L
    m, M, T = s["m"], s["lines"], s["tag"]
    o = ["import LayeredWitnessSupport", "import LayeredIntrinsicExample", "import LayeredMonotoneCheckerProofs", "",
         f"/-! Measured instance {T} ({s['function']}), seed {meas.rec['seed']}: generated by research/layered-networks/lean.py. -/",
         "", f"namespace LearnedCoincidence.Layered.Dev{T}", "",
         "open TwoLayer (ReadObservation SlotTiming)", "open MonotoneDNF.PremiseCheck (patterns)",
         "open MonotoneDNF (InverterTiming rails)", "", "set_option maxRecDepth 100000", "set_option maxHeartbeats 0", "set_option linter.unusedVariables false", ""]
    widths = [M] + [len(n) for n in s["layers"]]
    for k, nodes in enumerate(s["layers"], start=1):
        o.append(f"def timing{k} : SlotTiming := ⟨{q(tim['skew'][k])}, {q(tim['deadline'][k])}, {q(tim['duration'][k])}⟩")
        for i, n in enumerate(nodes):
            src = n["source"]
            sv = lambda a: "none" if src[a] is None else f"some {src[a]}"
            stim = [("pattern " + lst(str(j) for j in sorted(x))) if x is not None else "pattern []" for x in n["stimulus"]]
            o.append(f"def node{k}_{i} : Node {M} {widths[k - 1]} := ⟨{{ canonical .{n['gate']} with maxWrites := {maxw[(k, i)]} }}, "
                     f"fun a => if a.val = 0 then {sv(0)} else {sv(1)}, fun _ => {q(tim['delta'])}, "
                     f"fun g => if g.val = 0 then {stim[0]} else {stim[1]}⟩")
        lower = f"(Cascade.input : Cascade {M} 0 {M})" if k == 1 else f"layer{k - 1}"
        sel = " else ".join(f"if i.val = {i} then node{k}_{i}" for i in range(len(nodes) - 1))
        body = f"{sel} else node{k}_{len(nodes) - 1}" if len(nodes) > 1 else f"node{k}_0"
        o += [f"def layer{k} : Cascade {M} {k} {len(nodes)} := .layer {lower} timing{k} fun i => {body}", ""]
    o += [f"def circuit := layer{L}", f"def layer0 : Cascade {M} 0 {M} := Cascade.input", ""]
    o += ["def blankRead : ReadObservation 2 := ⟨0, fun _ => none, [], 0⟩",
          "def blankInv : ReadObservation 1 := ⟨0, fun _ => none, [], 0⟩",
          "def arr2 (a b : Option Rat) : Fin 2 → Option Rat := fun j => if j.val = 0 then a else b", "",
          "/-- A trace constructor from data rows (top layer first) and the line arrivals. No proof obligation. -/",
          "def build : (c : Cascade M L N) → List (List (ReadObservation 2)) → List (Option Rat) → ReadTrace c",
          "  | .input, _, ext => fun j => ext.getD j.val none",
          "  | .layer lower _ _, rows, ext => ⟨build lower rows.tail ext, fun i => (rows.headD []).getD i.val blankRead, fun _ _ => 0⟩", "",
          "def routedAll : (c : Cascade M L N) → ReadTrace c → Bool",
          "  | .input, _ => true",
          "  | .layer lower _ nodes, r => routedAll lower r.1 && (List.finRange _).all fun i => Checker.routed (nodes i) (pulseDates lower r.1) (r.2.1 i)", ""]
    off = " else ".join(f"if k = {k} then {q(v)}" for k, v in sorted(tim["offset"].items()) if k < L) + f" else {q(tim['offset'][L])}"
    o += [f"def sched (T : Rat) : Nat → Rat := fun k => T + ({off})",
          "def dmin : Nat → Rat := fun k => " + " else ".join(f"if k = {k} then {q(dmin[k])}" for k in range(1, L)) + (" else " if L > 1 else "") + q(dmin[L]),
          "def dmax : Nat → Rat := fun k => " + " else ".join(f"if k = {k} then {q(dmax[k])}" for k in range(1, L)) + (" else " if L > 1 else "") + q(dmax[L]),
          f"def w : Rat := {q(tim['w'])}",
          "def lhigh : Nat → Rat := fun k => layerSkew circuit k + dmax k", ""]
    if s["front"]:
        o.append(f"def front : InverterTiming := ⟨{q(tim['inverter_window'])}, {q(tim['emit_early'])}, {q(tim['emit_late'])}⟩")
    # tests, by pattern code
    tests = meas.tests()
    o.append("def testT : Nat → Rat")
    o += [f"  | {k} => {q(meas.d(t['T']))}" for k, t in enumerate(tests)] + ["  | _ => 0"]
    o.append("def testData : Nat → List (List (ReadObservation 2)) × List (Option Rat)")
    o += [f"  | {k} => ({rows(meas.trace(t, L))}, {lst(opt(x) for x in meas.lines(t))})" for k, t in enumerate(tests)] + ["  | _ => ([], [])"]
    o.append("def test (k : Nat) : ReadTrace circuit := build circuit (testData k).1 (testData k).2")
    if s["front"]:
        o.append("def testInv : Nat → List (ReadObservation 1)")
        o += [f"  | {k} => {lst(read1(v) for v in meas.inverters(t))}" for k, t in enumerate(tests)] + ["  | _ => []"]
        o.append("def testExt (k : Nat) (y : Pattern " + str(m) + ") : Fin " + str(m) + " → Option Rat := fun j => if y j then some (testT k) else none")
        o.append(f"def testInvs (k : Nat) : Fin {m} → ReadObservation 1 := fun j => (testInv k).getD j.val blankInv")
    o.append(f"def code (y : Pattern {m}) : Nat := (List.finRange {m}).foldl (fun acc j => acc + if y j then 2 ^ j.val else 0) 0")
    o.append("def expect : Nat → Bool")
    o += [f"  | {k} => {bl(v)}" for k, v in enumerate(s["expect"])] + ["  | _ => false", ""]
    # lessons
    o.append("def lessonRow : Nat → Nat → Nat → Nat → Rat × List (List (ReadObservation 2)) × List (Option Rat) × ReadObservation 2")
    for (k, i, g, r), sl in sorted(lessons.items()):
        tr = meas.trace(sl, k)
        o.append(f"  | {k}, {i}, {g}, {r} => ({q(meas.d(sl['T']))}, {rows(tr[:-1])}, {lst(opt(x) for x in meas.lines(sl))}, {read2(tr[-1][i])})")
    o.append("  | _, _, _, _ => (0, [], [], blankRead)")
    o += ["def buildTrain : (c : Cascade M L N) → TrainingTrace c",
          "  | .input => ()",
          "  | .layer (L := L) lower _ _ => ⟨buildTrain lower,",
          "      fun i g r => build lower (lessonRow (L + 1) i.val g.val r).2.1 (lessonRow (L + 1) i.val g.val r).2.2.1,",
          "      fun i g r => (lessonRow (L + 1) i.val g.val r).2.2.2⟩",
          "def train : TrainingTrace circuit := buildTrain circuit",
          "def clock : LessonClock := fun l i g r => sched (lessonRow l i g r).1", ""]
    if s["front"]:
        o.append("def lessonInv : Nat → Nat → Nat → Nat → List (ReadObservation 1)")
        for (k, i, g, r), sl in sorted(lessons.items()):
            o.append(f"  | {k}, {i}, {g}, {r} => {lst(read1(v) for v in meas.inverters(sl))}")
        o.append("  | _, _, _, _ => []")
    # the checks
    rep, _, _, _, _ = meas.report()
    tests_rep = rep["tests"]
    allt = lambda key: all(t[key] for t in tests_rep)
    vals = dict(valid=True, chain=rep["summary"]["chain"])
    o += ["", "theorem valid_check : checkLayeredValid circuit = true := by decide +kernel",
          f"theorem chain_check : checkChainDates (sched 0) (latencyLow dmin) (latencyHigh w lhigh) circuit = {bl(vals['chain'])} := by decide +kernel"]
    pats = f"(patterns {m}).all fun y => let k := code y;"
    checks = [("scheduled", "checkScheduled (sched (testT k)) circuit (test k)", allt("scheduled")),
              ("intrinsic", "checkIntrinsicDelays dmin dmax circuit (test k)", allt("intrinsic")),
              ("latency", "checkLatencies dmin lhigh circuit (test k)", allt("latency")),
              ("routed", "routedAll circuit (test k)", allt("routed")),
              ("output", "observed circuit (test k) 0 == expect k", rep["summary"]["outputs"]),
              ("predicted", ("circuit.predict (rails y) 0 == expect k" if s["front"] else "circuit.predict y 0 == expect k"), True)]
    if s["front"]:
        checks += [("front", "checkLayeredFront front (testT k) (testExt k y) (testInvs k) circuit (test k)", allt("front")),
                   ("realised", f"(List.finRange {m}).all fun j => (testExt k y j).isSome == y j", allt("realised"))]
    else:
        checks += [("external", "checkExternalWindow (sched (testT k) 0) w circuit (test k)", allt("external_window")),
                   ("realised", f"(List.finRange {m}).all fun j => (inputTrace circuit (test k) j).isSome == y j", allt("realised"))]
    for name, expr, v in checks:
        o.append(f"theorem test_{name} : ({pats} {expr}) = {bl(v)} := by decide +kernel")
    if s["front"]:
        o.append("theorem front_fit : (∀ T, sched T 0 = T + front.emitEarly) ∧ front.window ≤ w ∧ front.emitLate - front.emitEarly ≤ w := by")
        o.append("  refine ⟨fun T => ?_, by decide +kernel, by decide +kernel⟩")
        o.append("  simp [sched, front]")
    lrep = rep["summary"]["lessons"]
    o += [f"theorem lesson_scheduled : checkTrainingScheduled clock circuit train = {bl(lrep['scheduled'])} := by decide +kernel",
          f"theorem lesson_chain : checkTrainingChainDates clock (latencyLow dmin) (latencyHigh w lhigh) circuit = {bl(rep['summary']['chain'])} := by decide +kernel",
          f"theorem lesson_pulses : checkTrainingPulses clock (latencyLow dmin) (latencyHigh w lhigh) circuit train = {bl(lrep['pulses'])} := by decide +kernel"]
    for k in range(1, L + 1):
        keys = sorted(x for x in lessons if x[0] == k)
        lk = lst(f"({i}, {g}, {r})" for (_, i, g, r) in keys)
        lower = f"layer{k - 1}"
        expr = (f"({lk} : List (Nat × Nat × Nat)).all fun (i, g, r) => let x := lessonRow {k} i g r; "
                f"checkIntrinsicDelay (dmin {k}) (dmax {k}) x.2.2.2 && checkIntrinsicDelays dmin dmax {lower} (build {lower} x.2.1 x.2.2.1)")
        o.append(f"theorem lesson_intrinsic_{k} : ({expr}) = {bl(lrep['intrinsic'])} := by decide +kernel")
        if s["front"]:
            expr = (f"({lk} : List (Nat × Nat × Nat)).all fun (i, g, r) => let x := lessonRow {k} i g r; "
                    f"checkLayeredFront front x.1 (fun (j : Fin {m}) => ((lessonInv {k} i g r).getD j.val blankInv).arrival 0) "
                    f"(fun (j : Fin {m}) => (lessonInv {k} i g r).getD j.val blankInv) {lower} (build {lower} x.2.1 x.2.2.1)")
            o.append(f"theorem lesson_front_{k} : ({expr}) = {bl(lrep['front'])} := by decide +kernel")
    o += ["", f"end LearnedCoincidence.Layered.Dev{T}", ""]
    return "\n".join(o)


def build_modules(cfg, build):
    """Compile the imported modules once (unchanged sources) into `build`."""
    src = (HERE / cfg["lean"]["dir"]).resolve()
    build.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ, LEAN_PATH=str(build))
    for mod in cfg["lean"]["modules"]:
        ol = build / f"{mod}.olean"
        if ol.exists() and ol.stat().st_mtime >= (src / f"{mod}.lean").stat().st_mtime:
            continue
        p = subprocess.run(["lean", "-o", str(ol), f"{mod}.lean"], cwd=src, env=env, capture_output=True, text=True, timeout=3600)
        if p.returncode:
            raise RuntimeError(f"{mod}: {p.stdout[-2000:]}{p.stderr[-2000:]}")


def check(cfg, path, build):
    env = dict(os.environ, LEAN_PATH=str(build))
    t0 = time.time()
    p = subprocess.run(["lean", "-DwarningAsError=true", str(path)], cwd=path.parent, env=env, capture_output=True,
                       text=True, timeout=7200)
    return dict(accepted=p.returncode == 0, seconds=round(time.time() - t0, 1), output=(p.stdout + p.stderr)[-4000:])

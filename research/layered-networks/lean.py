"""The Lean file of one measured instance, and its check by `decide +kernel`.

The file imports the layered modules of research/learned-coincidence (compiled once into build/, unchanged) and
defines, for the instance:
  the cascade (cells are `canonical` placeholders with maxWrites = the rounds run - 1; the timing, wiring, delays and
  stimuli are those of the run), the measured test traces and training trace (built from data tables by `build`, a
  trace constructor with no proof obligation, like `simulate` in LayeredWitnessSupport.lean), the schedule, the lesson
  clock, dmin and dmax per layer and, with a front end, the inverter timing and reads.
Each theorem states the value of a library checker on that data, the value computed in Python by measure.py:
  checkLayeredValid, checkChainDates (lambda_max = skew + dmax), and per test pattern checkScheduled,
  checkIntrinsicDelays, checkLatencies, checkLayeredFront or checkExternalWindow, the realised external pattern, the
  observed output against the expected function; per lesson checkTrainingScheduled, checkTrainingChainDates,
  checkTrainingPulses and the intrinsic delays and front end of each lesson.
  `routedAll` walks the cascade with the library's `routed` Boolean (LayeredMonotoneCheckerTargets.lean); this walk
  has no soundness proof here.
The file compiles only if the kernel agrees with every stated value.
Not emitted: the calibration checkers (checkLayeredTrainingCalibration, checkLayeredReadCalibration). They need
measured scores in calibration units and fitted cell parameters, which this run does not produce.
"""

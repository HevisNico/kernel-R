"""Retrospective need-budget diagnostic; never a circuit theorem certificate.

Reproduce the published peak-based ceiling comparison, then apply the room
formula to explicitly named proxies. No threshold error is measured here.
See NEED_TEST_PROTOCOL.md. No simulator is invoked and no results are changed.
"""
import argparse
import csv
import hashlib
import math
from pathlib import Path
import statistics

from analyze import Campaign, VR0, cell_view


FIELDS = [
    "run", "port", "qualification", "missing_reason", "observed_silent",
    "trip_proxy", "first_swing", "dose_samples", "d0_proxy", "d0_source",
    "gap_proxy", "ceiling_count", "count_agrees", "a_proxy", "b_sample",
    "ell_assumed", "room_proxy", "proxy_passes",
]


def proxy_budget(first_swing, trip, doses, fallback=None):
    """A descriptive calculation, with ell ASSUMED zero, not estimated.

    The sample maximum is not a bound on all writes. No samples means a
    missing b, even if the pooled dose lets us reproduce the old ceiling.
    """
    if not all(math.isfinite(x) and x > 0 for x in (first_swing, trip)):
        raise ValueError("positive finite swings required")
    if any(not math.isfinite(x) for x in doses):
        raise ValueError("nonfinite dose")
    d0 = statistics.mean(doses) if doses else fallback
    if d0 is None or not math.isfinite(d0) or d0 <= 0:
        raise ValueError("positive finite dose estimate unavailable")
    gap_log = math.log(trip / first_swing)
    gap = gap_log / d0
    m = max(0, math.ceil(gap))
    a = abs((m - 0.5) * d0 - gap_log)
    b = max(abs(d - d0) for d in doses) if doses else None
    room = None if b is None else d0 / 2 - a - m * b - 1 / 8000
    return dict(d0_proxy=d0, d0_source="port" if doses else "pooled_fallback",
                gap_proxy=gap, ceiling_count=m, a_proxy=a, b_sample=b,
                ell_assumed=0.0, room_proxy=room,
                proxy_passes=None if room is None else room > 0)


def analyze(results):
    campaign = Campaign(str(results))
    names = campaign.series("mc_")
    records, samples = [], []
    for name in names:
        for q in (1, 2):
            row = dict.fromkeys(FIELDS)
            row.update(run=name, port=q, qualification="not_evaluable",
                       missing_reason="independent calibration, threshold and full write bounds; execution linkage")
            records.append(row)
            if name not in campaign.rows:
                row["missing_reason"] = campaign.state[name][1]
                continue
            cell = cell_view(name, campaign.rows[name])
            p = cell["p"][q - 1]
            swings = [VR0 - v for v in p["vq_min"]]
            firing = [VR0 - x["vq_min"] for x in cell["rows"]
                      if x["fired"] and x["port"] in (1, 2)]
            if not p["stopped"] or not swings or not firing or p["silent"] == 0:
                row["missing_reason"] += "; no complete silent-to-first-fire comparison"
                continue
            if any(not math.isfinite(s) or s <= 0 for s in swings + firing):
                row["missing_reason"] += "; invalid swing"
                continue
            # Exactly the historical estimator: only consecutive peaks before
            # first FIRE. Thus the last silent write is NOT observed by this proxy.
            doses = [math.log(swings[j + 1] / swings[j]) for j in range(p["silent"] - 1)]
            row.update(observed_silent=p["silent"], trip_proxy=statistics.median(firing),
                       first_swing=swings[0], dose_samples=len(doses))
            samples.append((row, doses))
    pooled = [d for _, doses in samples for d in doses]
    fallback = statistics.mean(pooled) if pooled else None
    for row, doses in samples:
        try:
            row.update(proxy_budget(row["first_swing"], row["trip_proxy"], doses, fallback))
            row["count_agrees"] = row["observed_silent"] == row["ceiling_count"]
        except ValueError as exc:
            row["missing_reason"] += "; " + str(exc)
    digest = hashlib.sha256()
    for name in names:
        path = Path(results) / (name + ".csv")
        digest.update((name + "\0").encode())
        digest.update(path.read_bytes() if path.exists() else b"MISSING")
    return records, digest.hexdigest()


def render(rows, digest):
    def count(status, agrees):
        return sum(r["proxy_passes"] is status and r["count_agrees"] is agrees for r in rows)

    missing = sum(r["count_agrees"] is None for r in rows)
    disagree = [r for r in rows if r["count_agrees"] is False]
    passed_disagree = [r for r in disagree if r["proxy_passes"] is True]
    lines = [
        "# Retrospective need-budget diagnostic", "",
        "Generated by `python3 -B need_budget.py`. Rule: [NEED_TEST_PROTOCOL.md](NEED_TEST_PROTOCOL.md).",
        "This reuses already inspected simulations. It is not a preregistered test, a hardware measurement,",
        "or a verification that the circuit satisfies the Lean theorem's hypotheses.", "",
        f"All {len(rows)} planned mismatch/noise ports are retained. **The full theorem application is",
        f"not evaluable for all {len(rows)} ports**: independent calibrated gain, threshold and complete",
        "per-write bounds, and the scalar-to-execution linkage, are not available in these summary CSVs.", "",
        "## Fixed descriptive calculation", "",
        "For each cell, `trip` is the median main-capacitor swing over firing single-port pulses.",
        "For each port, `s_first` is its first-pulse swing. The dose samples are",
        "`log(s_next/s_current)` between consecutive silent peaks before the first FIRE.",
        "`d0` is their mean; the pooled mean is used only to reproduce the old ceiling when",
        "a port has no dose sample. Missing dispersion remains missing, not zero.", "",
        "```text",
        "g = log(trip / s_first)",
        "m_proxy = max(0, ceil(g / d0))",
        "a_proxy = abs((m_proxy - 1/2)*d0 - g)",
        "b_sample = max_j abs(dose_sample(j) - d0)",
        "ell_assumed = 0  # an optimistic assumption, NOT a measurement",
        "room_proxy = d0/2 - a_proxy - m_proxy*b_sample - 1/8000",
        "proxy_passes iff room_proxy > 0",
        "```", "",
        "The expression for `a_proxy` follows by normalizing the firing swing to the nominal",
        "threshold; it assumes the ideal gain-to-swing relation. This removes the reference",
        "response factor algebraically, but does not establish the physical calibration.", "",
        "## All ports, including disagreements", "",
        "| Proxy criterion | Ceiling agrees with observed count | Ceiling disagrees |",
        "|---|---:|---:|",
    ]
    for status, label in ((True, "Passes"), (False, "Fails"), (None, "Missing dispersion")):
        lines.append(f"| {label} | {count(status, True)} | {count(status, False)} |")
    lines += ["", f"Ports without a ceiling comparison: {missing}.", "",
              f"Ceiling disagreements passing the proxy criterion: {len(passed_disagree)} of {len(disagree)}.",
              "Thus even this optimistic surrogate does **not** give a perfect separation.", "",
              "| Run | Port | Observed silent | Ceiling | `a_proxy` | `b_sample` | `room_proxy` | Passes |",
              "|---|---:|---:|---:|---:|---:|---:|---|"]
    for r in disagree:
        vals = ["missing" if r[k] is None else f"{r[k]:.9g}" for k in ("a_proxy", "b_sample", "room_proxy")]
        lines.append(f"| {r['run']} | {r['port']} | {r['observed_silent']} | {r['ceiling_count']} | "
                     + " | ".join(vals) + f" | {r['proxy_passes']} |")
    lines += ["", "## Why this is not a test of the theorem's boundary", "",
              "- `trip` uses the same campaign's firing outcomes; the dose estimator is selected by",
              "  which pulses stayed silent. These are retrospective, outcome-dependent estimates.",
              "- The saved `vq_min` is a minimum over a whole period, not the main state at the",
              "  independent comparator threshold. Delay, overshoot and protection can change it.",
              "- The silent-peak estimator omits the final silent write, and read noise can change",
              "  consecutive peak ratios even if the actual stored gain increment is constant.",
              "- Storage voltages and digital window times are present, but calibrated log-gain,",
              "  sensor charge endpoints and current-transfer residuals for all writes are not.",
              "- A sample maximum is not a uniform dose bound; zero threshold error is not measured.",
              "- `room` is sufficient, not necessary. Correct counts outside it are allowed.", "",
              "No budget was increased to discard the remaining disagreement. The full per-port",
              "table is [need_budget_ports.csv](need_budget_ports.csv); blank values mean missing.", "",
              "Input fingerprint (SHA-256 of ordered run names plus CSV bytes, as implemented in the script):",
              f"`{digest}`", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=Path(__file__).parent / "results")
    parser.add_argument("--out", type=Path, default=Path(__file__).parent)
    args = parser.parse_args()
    rows, digest = analyze(args.results)
    args.out.mkdir(parents=True, exist_ok=True)
    with (args.out / "need_budget_ports.csv").open("w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=FIELDS, lineterminator="\n")
        writer.writeheader()
        # Round for portable report diffs; classification uses unrounded values.
        writer.writerows({k: format(v, ".12g") if isinstance(v, float) else v
                          for k, v in row.items()} for row in rows)
    (args.out / "NEED_BUDGET.md").write_text(render(rows, digest))
    print(f"Reported {len(rows)} planned ports; no full theorem qualification is inferred.")


if __name__ == "__main__":
    main()

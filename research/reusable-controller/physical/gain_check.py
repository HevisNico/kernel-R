"""Generate Lean-checked readout enclosures from pinned public decimal readings.

Only rational arithmetic is used here. Lean checks the Taylor remainder and
each generated bound independently. This encloses the reported scalar formula,
not the difference between that formula and an actual transistor-state gain.
"""
import argparse
import copy
from fractions import Fraction as Q
import hashlib
import json
from pathlib import Path

import evidence_check as evidence

HERE = Path(__file__).resolve().parent
GENERATED = HERE / 'PhysicalEvaluator/RecordedGains.lean'
DELTA = Q(1, 10000)  # illustrative admissible residual, NOT a measured error
GRID = 10**8


def down(x, grid=GRID):
    return Q((x * grid).__floor__(), grid)


def up(x, grid=GRID):
    return -down(-x, grid)


def series(x, n=6):
    t = (x - 1) / (x + 1)
    total = 2 * sum((t**(2*i+1) / (2*i+1) for i in range(n)), Q(0))
    tail = 2 * abs(t)**(2*n+1) / (1-t*t)
    return total-tail, total+tail


def literal(x):
    x = Q(x)
    return f'({x.numerator} / {x.denominator} : ℝ)'


def compute(data):
    ports = evidence.indexed(data['ports'])
    calibration = data['calibration']
    result = []
    for port in (1, 2):
        row = ports['t6004', port]
        m = int(row['m'])
        readings = [r for r in data['runs']['t6004']['rows'] if int(r['port']) == port][:m+1]
        evidence.require(len(readings) == m+1, 'complete gain prefix')
        values = []
        for i, r in enumerate(readings):
            fired = r['fired'] == '1'
            evidence.require(fired == (i == m), 'gain prefix ends at first FIRE')
            evidence.require(not fired or Q(r['fire_latency']) >= Q(76,100), 'early FIRE unsupported')
            q, c = Q(r['q_tc' if fired else 'q_peak']), Q(r['c_pre'])
            evidence.require(c >= Q(1,10), 'charge above rest')
            e0, e1 = ((Q(68728927,10**8), Q(68728929,10**8)) if fired else
                      (Q(60653065,10**8), Q(60653067,10**8)))
            x0 = down(q-Q(1,10)-(c-Q(1,10))*e1, 10**9)
            x1 = up(q-Q(1,10)-(c-Q(1,10))*e0, 10**9)
            evidence.require(x0 > 0, 'positive log input')
            y0, y1 = down(series(x0)[0]), up(series(x1)[1])
            kappa = calibration['kappa'] if fired else Q(0)
            values.append(dict(q=q, c=c, fired=fired, x0=x0, x1=x1,
                               y0=y0, y1=y1, kappa=kappa, lo=y0+kappa, hi=y1+kappa))
        dose, level = calibration['d0'], Q(row['level0'])
        center_log0, center_log1 = series(level-Q(1,10))
        center_log0, center_log1 = down(center_log0), up(center_log1)
        center0 = center_log0-(m-Q(1,2))*dose
        center1 = center_log1-(m-Q(1,2))*dose
        ahat = up(max(abs(values[0]['lo']-center1), abs(values[0]['hi']-center0)))
        bhat = up(max(max(abs(v['lo']-values[0]['hi']-i*dose),
                          abs(v['hi']-values[0]['lo']-i*dose)) for i,v in enumerate(values)))
        evidence.require(ahat+DELTA <= Q(row['a'])+evidence.PAD, 'centering residual budget')
        evidence.require(bhat+2*DELTA <= Q(row['B'])+evidence.PAD, 'cumulative residual budget')
        result.append(dict(port=port, m=m, values=values, ahat=ahat, bhat=bhat,
                           center_log0=center_log0, center_log1=center_log1, level=level))
    return result


def function(name, values):
    lines = [f'noncomputable def {name} (k : Fin {len(values)}) : ℝ :=', '  match k.val with']
    for i, value in enumerate(values):
        lines.append(f'  | {i if i+1<len(values) else "_"} => {value}')
    return '\n'.join(lines)


def render(results):
    lines = ['import PhysicalEvaluator.Readout', 'import PhysicalEvaluator.MeasuredGains',
             'import PhysicalEvaluator.RecordedData', '',
             '/-! Generated by gain_check.py from pinned decimal read summaries.',
             'Every log/exp enclosure is checked by Lean; the physical residual',
             'between inferred and true gain remains an explicit premise. -/',
             'namespace ReusableController.PhysicalEvaluator.RecordedGains',
             'open RecordedData', 'set_option maxRecDepth 4096', '']
    for case in results:
        p, m, values = case['port'], case['m'], case['values']
        name = f't6004p{p}'
        formulas = []
        for i, v in enumerate(values):
            g = f'{name}Read{i}'
            duration = '(3 / 8)' if v['fired'] else '(1 / 2)'
            formulas.append(g)
            exp = 'expMinusThreeEighths_bounds' if v['fired'] else 'expMinusHalf_bounds'
            lines += [f'noncomputable def {g} : ℝ :=',
                      f'  reportedReadGain {literal(v["q"])} {literal(v["c"])} {duration} {literal(v["kappa"])}',
                      f'theorem {g}_bounds : {literal(v["lo"])} ≤ {g} ∧ {g} ≤ {literal(v["hi"])} := by',
                      f'  have bounds := reportedReadGain_bounds 6 6',
                      f'    (q := {literal(v["q"])}) (c := {literal(v["c"])})',
                      f'    (kappa := {literal(v["kappa"])})',
                      f'    (xLo := {literal(v["x0"])}) (xHi := {literal(v["x1"])})',
                      f'    (yLo := {literal(v["y0"])}) (yHi := {literal(v["y1"])})',
                      f'    (by norm_num) {exp}.1 {exp}.2',
                      '    (by norm_num) (by norm_num) (by norm_num)',
                      '    (by norm_num [logTaylor, logTail, logArgument, Finset.sum_range_succ])',
                      '    (by norm_num [logTaylor, logTail, logArgument, Finset.sum_range_succ])',
                      f'  norm_num [{g}] at bounds ⊢', '  exact bounds', '']
        lines += [function(name+'Gain', formulas),
                  function(name+'Lower', [literal(v['lo']) for v in values]),
                  function(name+'Upper', [literal(v['hi']) for v in values]),
                  f'theorem {name}Gain_bounds (k : Fin {m+1}) :',
                  f'    {name}Lower k ≤ {name}Gain k ∧ {name}Gain k ≤ {name}Upper k := by',
                  '  fin_cases k']
        lines += [f'  · exact {name}Read{i}_bounds' for i in range(m+1)]
        lines += ['', f'noncomputable def {name}Ahat : ℝ := {literal(case["ahat"])}',
                  f'noncomputable def {name}Bhat : ℝ := {literal(case["bhat"])}',
                  f'theorem {name}Centre :',
                  f'    |{name}Gain 0 - reportedCentre {name}NominalLevel0 {name}Dose0 {m}| ≤ {name}Ahat := by',
                  f'  have g := {name}Gain_bounds 0',
                  f'  have c : {literal(case["center_log0"])} ≤ Real.log ({name}NominalLevel0 - 1/10) ∧',
                  f'      Real.log ({name}NominalLevel0 - 1/10) ≤ {literal(case["center_log1"])} := by',
                  '    apply log_bounds_of_taylor 6 (by norm_num ['+name+'NominalLevel0])',
                  '    all_goals norm_num ['+name+'NominalLevel0, logTaylor, logTail, logArgument, Finset.sum_range_succ]',
                  f'  norm_num [{name}Lower, {name}Upper] at g',
                  f'  dsimp [reportedCentre, {name}Ahat, {name}Dose0]',
                  '  exact abs_le.mpr ⟨by linarith [g.1, g.2, c.1, c.2], by linarith [g.1, g.2, c.1, c.2]⟩',
                  f'theorem {name}Cumulative (k : Fin {m+1}) :',
                  f'    |{name}Gain k - {name}Gain 0 - (k.val : ℝ) * {name}Dose0| ≤ {name}Bhat := by',
                  f'  have s := {name}Gain_bounds 0', f'  have g := {name}Gain_bounds k',
                  f'  norm_num [{name}Gain, {name}Lower, {name}Upper] at s',
                  '  fin_cases k',
                  f'  all_goals norm_num [{name}Gain, {name}Lower, {name}Upper] at g',
                  f'  all_goals norm_num [{name}Gain, {name}Dose0, {name}Bhat]',
                  '  all_goals exact abs_le.mpr ⟨by linarith [s.1, s.2, g.1, g.2], by linarith [s.1, s.2, g.1, g.2]⟩',
                  f'theorem {name}ResidualRoom :',
                  f'    {name}Ahat + 1/10000 ≤ {name}A ∧ {name}Bhat + 2*(1/10000) ≤ {name}B := by',
                  f'  norm_num [{name}Ahat, {name}Bhat, {name}A, {name}B]', '']
    lines += ['end ReusableController.PhysicalEvaluator.RecordedGains', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    blobs = {p.name: p.read_bytes() for p in evidence.EVIDENCE.iterdir()}
    evidence.integrity(blobs)
    data = evidence.parse(blobs)
    evidence.analyse(data)
    results = compute(data)
    generated = render(results)
    if args.check:
        evidence.require(GENERATED.read_text() == generated, 'stale generated gains')
    else:
        GENERATED.write_text(generated)
    def perturb_peak(d):
        d['runs']['t6004']['rows'][0]['q_peak'] = '0.85'
    def omit_kappa(d):
        d['calibration']['kappa'] = Q(0)
    def double_dose(d):
        d['calibration']['d0'] *= 2
    def early_fire(d):
        d['runs']['t6004']['rows'][6]['fire_latency'] = '0.5'
    controls = []
    for name, mutation in [('changed_peak', perturb_peak), ('missing_kappa', omit_kappa),
                           ('doubled_dose', double_dose), ('early_fire', early_fire)]:
        changed = copy.deepcopy(data)
        mutation(changed)
        try:
            compute(changed)
        except evidence.EvidenceError as error:
            controls.append(dict(mutation=name, rejected=True, reason=str(error)))
        else:
            raise RuntimeError('negative control accepted: '+name)
    report = dict(source_commit=evidence.COMMIT, arithmetic='exact rational Taylor enclosures; Lean checked separately',
                  generated_sha256=hashlib.sha256(generated.encode()).hexdigest(),
                  script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                  admissible_residual=str(DELTA), residual_is_measured=False,
                  ports=[dict(port=r['port'], samples=len(r['values']), ahat=str(r['ahat']), bhat=str(r['bhat'])) for r in results],
                  negative_controls=controls)
    if args.report:
        args.report.write_text(json.dumps(report, indent=2)+'\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()

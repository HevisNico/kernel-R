"""M4: writes the Lean files of tests (b), (c) and the controls of GENERATOR_DESIGN.md 4.2-4.4, with the mirror's
verdicts asserted, and REPORT.json with every verdict. Compilation is done afterwards by gencheck.sh (run_m4.sh).

  python -I tests/run_synth.py OUT_DIR

Files:
  Synth_<case>.lean   S0..S5, each at residual rules zero, plus, minus, seeded:7 (tags <case>_<rule>); per spec the
                      three per-checker theorems, the conjunction, the derivation of the outputs, and `function_*`: the
                      cascade's `output` against the stated function over the whole cube, written independently
  Mut_<base>.lean     the 15 mutations of mutate.py on S0 and S1 (seeded:7 base), plus `edge` (the plus-rule base with
                      one residual at budget + 1); every one asserts `checks = false`
  Reach.lean          comparable terms {A} and {A, B} (regenerated by synth, not a mutation): `reachable` fails
  Flip_<n>.lean       controls: copies of a passing and a failing file with one asserted Boolean flipped; each must
                      fail to compile with a `decide` error
"""
import json
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import emit  # noqa: E402
import mirror  # noqa: E402
import mutate  # noqa: E402
import spec  # noqa: E402
import synth  # noqa: E402

NS = "LearnedCoincidence.MonotoneDNF.PremiseCheck.Generated"

# case: (M, terms, lines, alwaysFire, {output: stated function}) -- the function is written independently of the terms
CASES = {
    "S0": (4, [{0, 1}, {2, 3}], [{0, 1}], None, {0: "(x 0 && x 1) || (x 2 && x 3)"}),
    "S1": (3, [{0, 1}, {1, 2}], [{0, 1}], None, {0: "x 1 && (x 0 || x 2)"}),
    "S2": (3, [{0, 1}, {2}], [{0, 1}], None, {0: "(x 0 && x 1) || x 2"}),
    "S3": (3, [{0, 1}, {0, 2}, {1, 2}], [{0, 1, 2}], None, {0: "decide (2 ≤ card x)"}),
    "S4": (4, [{0, 1}, {2, 3}], [{0, 1}, {0}], None, {0: "(x 0 && x 1) || (x 2 && x 3)", 1: "x 0 && x 1"}),
    "S5": (2, [], [set()], [True], {0: "true"}),
}
RULES = ("zero", "plus", "minus", "seeded:7")


def lean_spec(raw):
    raw = dict(raw, lean=dict(style="generic", namespace=NS, source="tests/run_synth.py (synthetic, additive model)", derive=True))
    return spec.load(raw)


def function_theorems(s, fns):
    out = ""
    for K in s["budgets"]:
        for i, expr in fns.items():
            out += (f"set_option maxRecDepth 100000 in\nset_option maxHeartbeats 0 in\n"
                    f"theorem function_{s['tag']}_{K}_{i} : ((patterns {s['M']}).all fun x => output cascade_{s['tag']}_{K} ({i} : Fin {s['B']}) x == ({expr})) = true := by decide +kernel\n\n")
    return out


def write(path, specs, extra=""):
    verdicts, pcs, rep = {}, {}, []
    for s in specs:
        for K, (conj, pc, fails) in mirror.verdicts(s).items():
            verdicts[(s["tag"], K)], pcs[(s["tag"], K)] = conj, pc
            rep.append(dict(file=path.name, tag=s["tag"], budget=K, shape=[s["A"], s["B"], s["M"]], mirror=conj, per_checker=pc,
                            failing_kinds=sorted({k for _, k, _ in fails}), physical=s["physical"]))
    path.write_text(emit.lean_file(specs, verdicts, f"tests/run_synth.py ({path.stem})", per_checker=pcs, extra=extra))
    return rep


def flips(src, dst_dir, prefix):
    """One copy of src per asserted `= true|false := by decide +kernel`, that Boolean flipped."""
    text = src.read_text()
    out = []
    ms = list(re.finditer(r"^(theorem (\S+) : .* = )(true|false)( := by decide \+kernel)$", text, flags=re.M))
    for k, m in enumerate(ms):
        flipped = "false" if m.group(3) == "true" else "true"
        new = text[:m.start()] + m.group(1) + flipped + m.group(4) + text[m.end():]
        p = dst_dir / f"{prefix}{k}.lean"
        p.write_text(new)
        out.append(dict(file=p.name, theorem=m.group(2), asserted_in_source=m.group(3)))
    return out


def main():
    od = Path(sys.argv[1])
    od.mkdir(parents=True, exist_ok=True)
    report = dict(cases=[], mutations=[], controls=[])
    bases = {}
    for case, (M, terms, lines, always, fns) in CASES.items():
        specs, extra = [], ""
        for rule in RULES:
            tag = f"{case}_{rule.replace(':', '')}"
            raw = synth.observation(synth.design(tag, M, terms, lines, always), rule)
            s = lean_spec(raw)
            specs.append(s)
            extra += function_theorems(s, fns)
            if rule == "seeded:7":
                bases[case] = raw
            if rule == "plus":
                bases[case + "_plus"] = raw
        report["cases"] += write(od / f"Synth_{case}.lean", specs, extra)
    for base in ("S0", "S1"):
        specs = [lean_spec(mutate.mutate(bases[base], name)) for name in mutate.KIND]
        edge = mutate.mutate(bases[base + "_plus"], "residual")
        edge["tag"] = f"{base}m_edge"
        specs.append(lean_spec(edge))
        rep = write(od / f"Mut_{base}.lean", specs)
        for r in rep:
            name = r["tag"].split("m_", 1)[1]
            want = mutate.KIND.get(name, {"residual"})
            r["intended_kinds"] = sorted(want)
            r["only_its_kind"] = bool(r["failing_kinds"]) and set(r["failing_kinds"]) <= want
        report["mutations"] += rep
    reach = synth.observation(synth.design("R0", 2, [{0}, {0, 1}], [{0, 1}]), "zero")
    report["mutations"] += [dict(r, intended_kinds=["reachable"], only_its_kind=set(r["failing_kinds"]) <= {"reachable"} and bool(r["failing_kinds"]))
                            for r in write(od / "Reach.lean", [lean_spec(reach)])]
    # controls: a passing file (S0 zero only) and a failing one (S0 residual only), each Boolean flipped in turn
    s0 = lean_spec(synth.observation(synth.design("C0", 4, [{0, 1}, {2, 3}], [{0, 1}]), "zero"))
    write(od / "Control_pass.lean", [s0])
    cf = lean_spec(mutate.mutate(bases["S0"], "residual") | {"tag": "C1"})
    write(od / "Control_fail.lean", [cf])
    report["controls"] += flips(od / "Control_pass.lean", od, "Flip_pass_") + flips(od / "Control_fail.lean", od, "Flip_fail_")
    # control: a missing row is refused
    bad = synth.observation(synth.design("C2", 4, [{0, 1}, {2, 3}], [{0, 1}]), "zero")
    bad["observation"]["teach"] = bad["observation"]["teach"][:-1]
    try:
        spec.load(bad)
        report["missing_row_refused"] = False
    except spec.SpecError as e:
        report["missing_row_refused"] = str(e)
    (od / "REPORT.json").write_text(json.dumps(report, indent=1) + "\n")
    print(f"cases: {len(report['cases'])} spec-budgets, all mirror-true: {all(r['mirror'] for r in report['cases'])}")
    print(f"mutations: {len(report['mutations'])}, all mirror-false: {not any(r['mirror'] for r in report['mutations'])}, "
          f"all only their kind: {all(r['only_its_kind'] for r in report['mutations'])}")
    for r in report["mutations"]:
        if not r["only_its_kind"]:
            print("  NOT ONLY ITS KIND:", r["tag"], r["failing_kinds"], r["intended_kinds"])
    print(f"controls: {len(report['controls'])} flipped files; missing row refused: {report['missing_row_refused']}")


if __name__ == "__main__":
    main()

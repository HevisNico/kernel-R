"""The one analysis of the campaign: words of the network runs from their waveforms, against PREDICTED.json.

  analyze.py OUT_DIR PREDICTED.json --measures EVIDENCE... --runs EVIDENCE...

EVIDENCE are the folders written by `launch.py collect`: those of the measures (small files are enough) and those
of the network runs (with their waveforms). Written in OUT_DIR: RESULTS.json and REPORT.md, as generated.

It follows PREDICTION.md and decides nothing: the eligible instances, the zero-error words and the control
instance are read in PREDICTED.json, which was committed before the network runs. It checks first that
PREDICTED.json is what `predicted.py` gives from the evidence of the measures, and that the runs found are the
runs it lists.
"""
import argparse
import json
from pathlib import Path
import statistics
import sys
import tempfile

HERE = Path(__file__).resolve().parent
NET = HERE.parent / "network-circuit"
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(NET))
sys.path.insert(0, str(NET / "phase1"))
import measure
import net
import plan
import predicted
import router

PORTS = plan.PORTS
TOLERANCE_MV = 0.01
SEPARATION = 16


def letter(tr, o):
    """The letter of one pulse, as PREDICTION.md defines the word of a port."""
    if o.get("refused"):
        return "r"
    if not o["delivered"]:
        return "x"
    c, q, date = o["cell"], o["port"], o["date_s"]
    if tr.at(f"v(x{c}.p)", date - 1e-9) > 0.9:
        return "-"
    fires = len(tr.crossings(f"v(x{c}.p)", date, date + net.TU + 2e-6))
    writes = len(tr.crossings(f"v(x{c}.x{q}.si)", date, date + net.CYCLE))
    return "F" if (fires, writes) == (1, 0) else "s" if (fires, writes) == (0, 1) else "?"


def network(evidence, doses, guarded):
    """Everything the analysis takes from one network run."""
    result = json.loads((evidence / "result.json").read_text())
    tr = measure.Trace(evidence / "trace.raw")
    horizon = router.ORIGIN + result["calendar"]["horizon"] * net.TU
    words, own, latencies, moves = {}, {}, {}, []
    occurrences = sorted(result["occurrences"], key=lambda o: o["date_s"])
    for name in PORTS:
        c, q = name[0], int(name[1])
        mine = [o for o in occurrences if f"{o['cell']}{o['port']}" == name]
        letters = [letter(tr, o) for o in mine]
        words[name] = "".join(letters)
        own[name] = "".join("r" if o.get("refused") else "x" if not o["delivered"] else "-" if o["protected_at_start"] else
                            "F" if o["fire"] and o[f"writes{q}"] == 0 else "s" if not o["fire"] and o[f"writes{q}"] == 1 else "?" for o in mine)
        latencies[name] = [(tr.crossings(f"v(x{c}.p)", o["date_s"], o["date_s"] + net.TU + 2e-6)[0] - o["date_s"]) / net.TU for o, x in zip(mine, letters) if x == "F"]
        u = lambda lo, hi: tr.u(c, q, lo, hi) * 1e3
        level = u(router.ORIGIN - 40e-6, router.ORIGIN - 5e-6)
        for o, x in zip(mine, letters):
            if not o["delivered"]:
                continue
            before, after = u(o["date_s"] - 30e-6, o["date_s"] - 2e-6), u(o["date_s"] + net.CYCLE - 30e-6, o["date_s"] + net.CYCLE - 2e-6)
            moves.append(dict(port=name, what="between its pulses", mV=before - level))
            moves.append(dict(port=name, what="pulse " + x, mV=(before - after) - (doses[name] if x == "s" else 0.0)))
            level = after
        moves.append(dict(port=name, what="between its pulses", mV=u(horizon - 30e-6, horizon - 2e-6) - level))
    dates = {c: sorted(o["date_s"] for o in occurrences if o["cell"] == c and o["delivered"]) for c in result["cells"]}
    separation = min((b - a) / net.TU for d in dates.values() for a, b in zip(d, d[1:]))
    worst = max(moves, key=lambda m: abs(m["mV"]))
    conditions = dict(no_pulse_refused=not any(o.get("refused") for o in occurrences), nothing_left_in_the_queue=not result["still_queued_at_the_horizon"],
                      stored_voltages_move_by_doses_only=abs(worst["mV"]) <= TOLERANCE_MV)
    if guarded:
        conditions["pulses_of_a_cell_16_units_apart"] = separation >= SEPARATION - 1e-9
    return dict(words=words, record_is_the_waveform=words == own, fires=len(result["fires"]), routed={e["name"]: sum(1 for o in occurrences if o["origin"] == e["name"]) for e in result["calendar"]["edges"]},
                least_separation_units=separation, largest_move_not_a_dose_mV=worst, conditions=conditions, latencies=latencies,
                wall_s=result["wall_s"], guard_units=result["guard_units"], calendar=result["calendar"]["name"])


def analyse(P, measure_folders, run_folders, **setup):
    """`setup` is empty for the campaign; the rehearsal gives the arguments of `predicted.build` that it used."""
    out = dict(what="analysis of the network campaign, generated by analyze.py; see PREDICTION.md")
    # 1. the predictions are those of the measures, and the runs are those of the predictions
    with tempfile.TemporaryDirectory() as tmp:
        predicted.build(tmp, [str(x) for x in measure_folders], **setup)
        out["predictions_are_those_of_the_measures"] = json.loads((Path(tmp) / "PREDICTED.json").read_text()) == P
    planned = P["network_runs"]
    found = predicted.gather(run_folders, planned)
    extra = sorted({r["id"] for f in map(Path, run_folders) for r in json.loads((f / "STATE.json").read_text())["records"]} - {r["id"] for r in planned})
    out["runs_not_in_the_predictions"] = extra
    measured_runs = predicted.gather(measure_folders, setup.get("runs") or plan.measure_runs(setup.get("which")))
    out["measure_runs"] = {k: v[0] for k, v in measured_runs.items()}
    out["network_runs"] = {k: v[0] for k, v in found.items()}
    # 2. every network run that counts
    runs = {}
    for r in planned:
        status, evidence = found[r["id"]]
        if status == "complete":
            doses = P["instances"][str(r["seed"])]["doses_mV"]
            runs[r["id"]] = dict(r, **network(evidence, doses, guarded=bool(r["guard"])), noise_fingerprint=json.loads((evidence / "record.json").read_text())["noise_fingerprint"])
    out["runs"] = runs
    by = lambda seed, scenario: [x for x in runs.values() if str(x["seed"]) == seed and x["scenario"] == scenario]
    # 3. D1 and D2
    tested, not_tested, d1, d2 = [], [], [], []
    for seed in P["eligible_instances"]:
        quiet = by(seed, "quiet")
        if not quiet:
            not_tested.append(seed)
            continue
        x, expected = quiet[0], P["instances"][seed]["zero_error_words"]
        tested.append(seed)
        d1.append(dict(instance=seed, run=x["id"], predicted=expected, observed=x["words"], ports_that_differ=[p for p in PORTS if x["words"][p] != expected[p]]))
        d2.append(dict(instance=seed, run=x["id"], conditions=x["conditions"], least_separation_units=x["least_separation_units"],
                       largest_move_not_a_dose_mV=x["largest_move_not_a_dose_mV"], record_is_the_waveform=x["record_is_the_waveform"]))
    verdict = lambda rows, good: "not established" if not rows else "holds" if all(good(r) for r in rows) else "fails"
    out["D1"] = dict(verdict=verdict(d1, lambda r: not r["ports_that_differ"]), eligible_instances=P["eligible_instances"], tested=tested, not_tested=not_tested, rows=d1)
    out["D2"] = dict(verdict=verdict(d2, lambda r: all(r["conditions"].values())), rows=d2)
    # 4. C1
    control = P["control_instance"]
    rows = by(control, "control") if control else []
    if rows:
        x, expected = rows[0], P["instances"][control]["zero_error_words"]
        differ = [p for p in PORTS if x["words"][p] != expected[p]]
        out["C1"] = dict(verdict="holds" if differ else "fails", instance=control, run=x["id"], predicted_by_the_predictor_that_ignores_the_help=expected, observed=x["words"],
                         ports_that_differ=differ, pulses_on_a_protected_cell=sum(w.count("-") for w in x["words"].values()), least_separation_units=x["least_separation_units"])
    else:
        out["C1"] = dict(verdict="not established", instance=control, why="no eligible instance" if control is None else "its run does not count")
    # 5. declared comparisons
    out["N2"] = [dict(instance=seed, run=x["id"], zero_error_words=P["instances"][seed]["zero_error_words"], observed=x["words"],
                      verdicts={p: P["instances"][seed]["noise_free"]["ports"][p]["verdict"] for p in PORTS},
                      ports_that_differ=[p for p in PORTS if x["words"][p] != P["instances"][seed]["zero_error_words"][p]])
                 for seed in P["measured_instances"] if seed not in P["eligible_instances"] for x in by(seed, "quiet")]
    marks = {}
    for run_id, (status, evidence) in measured_runs.items():
        if status == "complete" and "noisy" in run_id:
            marks.setdefault(run_id.split("-")[1], []).append((run_id, json.loads((evidence / "record.json").read_text())["noise_fingerprint"]))
    for x in runs.values():
        if x["scenario"] == "noisy":
            marks.setdefault(str(x["seed"]), []).append((x["id"], x["noise_fingerprint"]))
    duplicates = []
    for seed, rows in marks.items():
        seen = {}
        for run_id, mark in rows:
            if mark in seen:
                duplicates.append(dict(instance=seed, run=run_id, same_noise_as=seen[mark]))
            seen.setdefault(mark, run_id)
    out["noisy_runs_with_the_noise_of_an_earlier_run"] = duplicates
    skip = {d["run"] for d in duplicates}
    n1, n3 = [], []
    for seed in P["measured_instances"]:
        I = P["instances"][seed]
        quiet = by(seed, "quiet")
        for x in by(seed, "noisy"):
            if x["id"] in skip:
                continue
            verdicts = {p: I["noisy_k3"]["ports"][p]["verdict"] for p in PORTS} if "ports" in I["noisy_k3"] else dict.fromkeys(PORTS, "no noise measure")
            n1.append(dict(instance=seed, run=x["id"], full_room_at_k3=I["full_room_at_k3"], zero_error_words=I["zero_error_words"], observed=x["words"], verdicts=verdicts,
                           same_word={p: x["words"][p] == I["zero_error_words"][p] for p in PORTS},
                           same_writes={p: x["words"][p].count("s") == I["zero_error_words"][p].count("s") for p in PORTS}, conditions=x["conditions"]))
            for p in PORTS:
                port = I["constants"]["ports"][p]
                lat = x["latencies"][p]
                if quiet and len(lat) >= 3 and x["words"][p] == quiet[0]["words"][p] and quiet[0]["latencies"][p]:
                    slope = port["train_18_quiet"]["slope_per_mV"]
                    n3.append(dict(instance=seed, run=x["id"], port=p, fires=len(lat), offset_mV=(statistics.median(quiet[0]["latencies"][p]) - statistics.mean(lat)) / slope,
                                   within_sd_mV=statistics.stdev(lat) / slope, measured_within_mV=port.get("noise_within_run_mV"),
                                   measured_between_mV=I["constants"].get("noise_between_runs_mV")))
    out["N1"], out["N3"] = n1, n3
    return out


def report(R, P):
    L = ["# Network of R cells: report", "", "Generated by `analyze.py` from the evidence of the two machines. Not edited.", ""]
    L += ["## Checks before any count", "",
          f"- PREDICTED.json is what `predicted.py` gives from the evidence of the measures: **{'yes' if R['predictions_are_those_of_the_measures'] else 'NO'}**.",
          f"- Network runs outside the list of PREDICTED.json: {R['runs_not_in_the_predictions'] or 'none'}.",
          f"- Measure runs that do not count: {sorted(k for k, v in R['measure_runs'].items() if v != 'complete') or 'none'}.",
          f"- Network runs that do not count (missing runs): {sorted(k + ': ' + v for k, v in R['network_runs'].items() if v != 'complete') or 'none'}.",
          f"- Noisy runs with the noise of an earlier run: {R['noisy_runs_with_the_noise_of_an_earlier_run'] or 'none'}.", ""]
    L += ["## Instances", "", "| Instance | Machine | Measured | Eligible | Full room at K = 3 | Zero-error words a1, a2, b1, b2 |", "|---|---|---|---|---|---|"]
    for seed, I in P["instances"].items():
        words = ", ".join(f"`{I['zero_error_words'][p]}`" for p in PORTS) if I["measured"] else "-"
        L.append(f"| {seed} | {P['machine_of_each_instance'].get(seed, '-')} | {'yes' if I['measured'] else 'no: ' + json.dumps(I['why'])} | "
                 f"{('yes' if I['eligible'] else 'no') if I['measured'] else '-'} | {('yes' if I['full_room_at_k3'] else 'no') if I['measured'] else '-'} | {words} |")
    L += ["", f"Control instance: {P['control_instance']}.", "", "## Primary claim", "", f"**D1: {R['D1']['verdict']}.** Eligible instances: {R['D1']['eligible_instances'] or 'none'}; "
          f"tested: {R['D1']['tested'] or 'none'}; not tested: {R['D1']['not_tested'] or 'none'}.", ""]
    if R["D1"]["rows"]:
        L += ["| Instance | Port | Predicted | Observed | |", "|---|---|---|---|---|"]
        for row in R["D1"]["rows"]:
            L += [f"| {row['instance']} | `{p}` | `{row['predicted'][p]}` | `{row['observed'][p]}` | {'differs' if p in row['ports_that_differ'] else 'same'} |" for p in PORTS]
        L.append("")
    L += [f"**D2: {R['D2']['verdict']}.**", ""]
    if R["D2"]["rows"]:
        L += ["| Instance | Conditions that do not hold | Closest pulses on a cell, units | Largest move that is not a dose, mV |", "|---|---|---|---|"]
        for row in R["D2"]["rows"]:
            bad = [k for k, v in row["conditions"].items() if not v]
            m = row["largest_move_not_a_dose_mV"]
            L.append(f"| {row['instance']} | {bad or 'none'} | {row['least_separation_units']:.2f} | {m['mV']:+.4f} ({m['port']}, {m['what']}) |")
        L.append("")
    c = R["C1"]
    L += ["## Negative control", "", f"**C1: {c['verdict']}.** Instance: {c['instance']}." + ("" if "observed" in c else " " + c["why"] + "."), ""]
    if "observed" in c:
        L += ["| Port | Zero-error word | Observed at 8 units | |", "|---|---|---|---|"]
        L += [f"| `{p}` | `{c['predicted_by_the_predictor_that_ignores_the_help'][p]}` | `{c['observed'][p]}` | {'differs' if p in c['ports_that_differ'] else 'same'} |" for p in PORTS]
        L += ["", f"Pulses that arrived on a protected cell: {c['pulses_on_a_protected_cell']}. Closest pulses on a cell: {c['least_separation_units']:.2f} units.", ""]
    L += ["## Declared comparisons, not claims", "", "### N1. Noisy runs against the verdicts at K = 3", ""]
    if R["N1"]:
        L += ["| Instance | Run | Port | Verdict | Zero-error word | Observed | Same word | Same writes |", "|---|---|---|---|---|---|---|---|"]
        for row in R["N1"]:
            L += [f"| {row['instance']}{' (full room)' if row['full_room_at_k3'] else ''} | {row['run']} | `{p}` | {row['verdicts'][p]} | `{row['zero_error_words'][p]}` | `{row['observed'][p]}` | "
                  f"{'yes' if row['same_word'][p] else 'no'} | {'yes' if row['same_writes'][p] else 'no'} |" for p in PORTS]
        L.append("")
        for verdict in sorted({v for row in R["N1"] for v in row["verdicts"].values()}):
            cells = [(row["same_word"][p], row["same_writes"][p]) for row in R["N1"] for p in PORTS if row["verdicts"][p] == verdict]
            L.append(f"- \"{verdict}\": {sum(a for a, _ in cells)} of {len(cells)} port-runs with the zero-error word, {sum(b for _, b in cells)} with its writes.")
        L.append("")
    else:
        L += ["No noisy run counts.", ""]
    L += ["### N2. Runs without noise of the instances that are not eligible", ""]
    if R["N2"]:
        L += ["| Instance | Port | Verdict under the noise-free budget | Zero-error word | Observed | |", "|---|---|---|---|---|---|"]
        for row in R["N2"]:
            L += [f"| {row['instance']} | `{p}` | {row['verdicts'][p]} | `{row['zero_error_words'][p]}` | `{row['observed'][p]}` | {'differs' if p in row['ports_that_differ'] else 'same'} |" for p in PORTS]
        L.append("")
    else:
        L += ["None.", ""]
    L += ["### N3. Noise seen in the noisy network runs", ""]
    if R["N3"]:
        offsets = [x["offset_mV"] for x in R["N3"]]
        L += [f"{len(offsets)} port-runs with the word of the run without noise. Run offsets: {statistics.mean(o * o for o in offsets) ** 0.5:.3f} mV rms "
              f"(measured on the trains, per instance: {sorted({round(x['measured_between_mV'], 3) for x in R['N3'] if x['measured_between_mV'] is not None})}). "
              f"Scatter within a run: {statistics.mean(x['within_sd_mV'] ** 2 for x in R['N3']) ** 0.5:.3f} mV rms.", ""]
    else:
        L += ["No port-run to compare.", ""]
    L += ["## Runs", "", "| Run | Scenario | Words a1, a2, b1, b2 | FIRE | Closest pulses, units | Wall, s |", "|---|---|---|---|---|---|"]
    for x in R["runs"].values():
        L.append(f"| {x['id']} | {x['scenario']} | " + ", ".join(f"`{x['words'][p]}`" for p in PORTS) + f" | {x['fires']} | {x['least_separation_units']:.2f} | {x['wall_s']:.0f} |")
    return "\n".join(L) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("out", type=Path)
    p.add_argument("predicted", type=Path)
    p.add_argument("--measures", type=Path, nargs="+", required=True)
    p.add_argument("--runs", type=Path, nargs="+", required=True)
    a = p.parse_args()
    P = json.loads(a.predicted.read_text())
    R = analyse(P, a.measures, a.runs)
    (a.out / "RESULTS.json").write_text(json.dumps(R, indent=1) + "\n")
    (a.out / "REPORT.md").write_text(report(R, P))
    print(json.dumps({k: R[k]["verdict"] for k in ("D1", "D2", "C1")}))


if __name__ == "__main__":
    main()
